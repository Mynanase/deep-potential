def sample_model_velocity(flow_dir, checkpoint, pos, k, z0, eqx, jax, jnp, fit_all,
                          chunk=CHUNK_POS, verify=True, tag=""):
    """K draws of v ~ p_theta(v|x) at every position, with explicit base noise.

    The base noise `z0` is passed in, so the SAME standard-normal draws are used
    for every checkpoint and every model (common random numbers); the transform
    is the one `ConditionalPhaseSpaceFlow.sample` uses, and the first chunk is
    cross-checked against that builtin sampler before anything is accepted.

    The flow works in CARTESIAN velocity; the spherical basis (v_r, v_theta,
    v_phi) is applied here, once, so that no caller can compare a Cartesian draw
    against the spherical truth columns.
    """
    flow = fit_all.load_flow(Path(flow_dir), checkpoint_index=checkpoint)
    cvf = flow.conditional_velocity_flow

    @eqx.filter_jit
    def stage(cvf_, z, x):
        cond = (x - cvf_.cond_mean) / cvf_.cond_std
        return jax.vmap(lambda z_, c_: cvf_.flow.bijection.transform(z_, condition=c_))(
            z.reshape(-1, 3), jnp.repeat(cond, k, axis=0)).reshape(-1, k, 3)

    if verify:
        key_chk = jax.random.key(11)
        n_chk = min(256, len(pos))
        z_chk = cvf.flow.base_dist.sample(key_chk, (n_chk,)).block_until_ready()
        explicit = np.asarray(stage(cvf, np.tile(np.asarray(z_chk)[:, None, :], (1, k, 1)),
                                    jnp.asarray(pos[:n_chk])))
        builtin = np.asarray(cvf.sample(key_chk, n_chk, condition=jnp.asarray(pos[:n_chk])))
        dmax = float(np.abs(explicit[:, 0] - builtin).max())
        print(f"  guard {tag}: max|explicit-builtin| = {dmax:.2e}", flush=True)
        assert dmax < 2e-2, f"explicit sampling does not match NormalizingFlow.sample for {tag}"

    out = np.empty((len(pos), k, 3), dtype=np.float32)
    for i in range(0, len(pos), chunk):
        sl = slice(i, min(i + chunk, len(pos)))
        out[sl] = np.asarray(stage(cvf, z0[sl], jnp.asarray(pos[sl])))
    flat, flags = sph_vel(np.repeat(np.asarray(pos), k, axis=0), out.reshape(-1, 3))
    del flow, cvf, stage
    jax.clear_caches()
    return flat.reshape(len(pos), k, 3), flags


