def basis_flags(pos):
    """Degeneracy of the spherical velocity basis at these positions.

    R = 0 (polar axis) leaves v_theta/v_phi without a direction and r = 0
    leaves all three without one; both are reported, never silently NaN.
    """
    pos = np.asarray(pos, dtype=np.float64)
    r = np.linalg.norm(pos, axis=1)
    R = np.hypot(pos[:, 0], pos[:, 1])
    return dict(n_degenerate_r=int(np.count_nonzero(r <= BASIS_MIN)),
                n_degenerate_R=int(np.count_nonzero(R <= BASIS_MIN)),
                min_r=float(r.min()), min_R=float(R.min()))


def sph_vel(pos, vel_cart):
    """Cartesian -> spherical velocity basis (v_r, v_theta, v_phi).

    Same convention as the phase-1 audit (`utils.calc_coords`), origin (0,0,0),
    no rotation.  Returns the components plus the degeneracy flags, so callers
    can count and report rather than propagate a silent NaN.
    """
    pos = np.asarray(pos, dtype=np.float64)
    vel_cart = np.asarray(vel_cart, dtype=np.float64)
    x, y, z = pos[:, 0], pos[:, 1], pos[:, 2]
    vx, vy, vz = vel_cart[:, 0], vel_cart[:, 1], vel_cart[:, 2]
    r = np.linalg.norm(pos, axis=1)
    R = np.hypot(x, y)
    ok_r = r > BASIS_MIN
    ok_R = R > BASIS_MIN
    safe_r = np.where(ok_r, r, 1.0)
    safe_R = np.where(ok_R, R, 1.0)
    vr = (x * vx + y * vy + z * vz) / safe_r
    vth = (z * vr - safe_r * vz) / safe_R
    vT = (-vx * y + vy * x) / safe_R
    out = np.stack([np.where(ok_r, vr, np.nan),
                    np.where(ok_r & ok_R, vth, np.nan),
                    np.where(ok_r & ok_R, vT, np.nan)], axis=1)
    return out, basis_flags(pos)


def wmean(a, w):
    return float(np.sum(w * a) / np.sum(w))


def wstd(a, w):
    """Centred weighted standard deviation (not an RMS speed)."""
    mu = wmean(a, w)
    return float(np.sqrt(np.sum(w * (a - mu) ** 2) / np.sum(w)))


def wcorr(a, b, w):
    """Weighted Pearson correlation; NaN when either spread is degenerate."""
    ws = np.sum(w)
    ma = np.sum(w * a) / ws
    mb = np.sum(w * b) / ws
    da, db = a - ma, b - mb
    caa = np.sum(w * da * da) / ws
    cbb = np.sum(w * db * db) / ws
    if caa <= SIGMA_MIN ** 2 or cbb <= SIGMA_MIN ** 2:
        return float("nan")
    return float(np.sum(w * da * db) / ws / np.sqrt(caa * cbb))


def w1(a, wa, b, wb):
    """Mass-weighted Wasserstein-1 on the full, uncut samples (km/s in, km/s out)."""
    return float(wasserstein_distance(a, b, u_weights=wa, v_weights=wb))


def n_eff(w):
    return float(np.sum(w) ** 2 / np.sum(w ** 2))


def pct_ci(vals, lo=2.5, hi=97.5):
    v = np.asarray(vals, dtype=np.float64)
    v = v[np.isfinite(v)]
    if v.size == 0:
        return float("nan"), float("nan")
    return float(np.percentile(v, lo)), float(np.percentile(v, hi))


def component_stats(v_true, w_true, v_gen, w_gen, kms=KMS):
    """Per-component W1 / mean / centred sigma plus the three pair correlations.

    Every quantity is computed from the same samples; non-finite entries are
    excluded per component and counted by the caller through `n_invalid`.
    """
    out = {"n_invalid_rows": int(np.count_nonzero(~np.isfinite(v_gen).all(axis=1)))}
    for c, name in enumerate(COMP):
        t, g = v_true[:, c], v_gen[:, c]
        mt, mg = np.isfinite(t), np.isfinite(g)
        tt, wt = t[mt], w_true[mt]
        gg, wg = g[mg], w_gen[mg]
        rec = dict(n_invalid=int((~mg).sum()))
        if tt.size and gg.size:
            rec["w1"] = kms * w1(tt, wt, gg, wg)
            rec["mean_true"] = kms * wmean(tt, wt)
            rec["mean_gen"] = kms * wmean(gg, wg)
            rec["sigma_true"] = kms * wstd(tt, wt)
            rec["sigma_gen"] = kms * wstd(gg, wg)
            rec["dmean"] = rec["mean_gen"] - rec["mean_true"]
            rec["dsigma"] = rec["sigma_gen"] - rec["sigma_true"]
        else:
            for k in ("w1", "mean_true", "mean_gen", "sigma_true", "sigma_gen",
                      "dmean", "dsigma"):
                rec[k] = float("nan")
        out[name] = rec
    for (a, b) in PAIRS:
        ia, ib = COMP.index(a), COMP.index(b)
        ta, tb = v_true[:, ia], v_true[:, ib]
        ga, gb = v_gen[:, ia], v_gen[:, ib]
        mt = np.isfinite(ta) & np.isfinite(tb)
        mg = np.isfinite(ga) & np.isfinite(gb)
        rt = wcorr(ta[mt], tb[mt], w_true[mt]) if mt.any() else float("nan")
        rg = wcorr(ga[mg], gb[mg], w_gen[mg]) if mg.any() else float("nan")
        out[a + "|" + b] = dict(rho_true=rt, rho_gen=rg,
                                 drho=(rg - rt) if np.isfinite(rt) and np.isfinite(rg)
                                 else float("nan"),
                                 n_invalid=int((~mg).sum()))
    return out


def bootstrap_bin(v_true_b, w_true_b, gen_b, k, rng, b_boot):
    """Paired position bootstrap for one bin; returns arrays of length b_boot.

    `gen_b` is the (n_b, K, 3) generated block of ONE bin for one model.  The
    truth side is resampled with the same position draw, so the pairing the
    plan requires is kept exactly.
    """
    n_b = len(w_true_b)
    acc = {f"{q}|{n}": [] for q in ("w1", "dmean", "dsigma") for n in COMP}
    acc.update({f"drho|{a}|{b}": [] for (a, b) in PAIRS})
    for _ in range(b_boot):
        s = rng.integers(0, n_b, n_b)
        ws = w_true_b[s]
        rec = component_stats(v_true_b[s], ws, gen_b[s].reshape(-1, 3),
                              np.repeat(ws, k) / k)
        for n in COMP:
            acc[f"w1|{n}"].append(rec[n]["w1"])
            acc[f"dmean|{n}"].append(rec[n]["dmean"])
            acc[f"dsigma|{n}"].append(rec[n]["dsigma"])
        for (a, b) in PAIRS:
            acc[f"drho|{a}|{b}"].append(rec[a + "|" + b]["drho"])
    return {k_: (pct_ci(v)[0], pct_ci(v)[1]) for k_, v in acc.items()}


def block_bootstrap_bin(v_true_b, w_true_b, gen_b, k, block_b, rng, b_block):
    """Angular block bootstrap sensitivity: resample (cos-theta, phi) cells."""
    cells = np.unique(block_b)
    if block_b.size == 0 or cells.size < 2:
        return {n: (float("nan"), float("nan")) for n in COMP}, int(cells.size)
    members = [np.where(block_b == c)[0] for c in cells]
    acc = {n: [] for n in COMP}
    for _ in range(b_block):
        pick = rng.integers(0, cells.size, cells.size)
        sel = np.concatenate([members[i] for i in pick])
        ws = w_true_b[sel]
        rec = component_stats(v_true_b[sel], ws, gen_b[sel].reshape(-1, 3),
                              np.repeat(ws, k) / k)
        for n in COMP:
            acc[n].append(rec[n]["w1"])
    return {n: pct_ci(v) for n, v in acc.items()}, int(cells.size)


def truth_halfsplit_bin(v_true_b, w_true_b, rng, b_split):
    """W1 between two random halves of the same truth sample: reference scale.

    Each half has the same position count as the model comparison side only in
    the sense that it is the same stars; its own sample size is n_b/2, so this
    is a scale, not a lower bound and not something to subtract.
    """
    n_b = len(w_true_b)
    acc, n_eff_half = {n: [] for n in COMP}, []
    for _ in range(b_split):
        flip = rng.random(n_b) < 0.5
        if flip.all() or (~flip).all():
            continue
        a, b = np.where(flip)[0], np.where(~flip)[0]
        n_eff_half.append(n_eff(w_true_b[a]))
        for c, n in enumerate(COMP):
            xa, xb = v_true_b[a, c], v_true_b[b, c]
            ma, mb = np.isfinite(xa), np.isfinite(xb)
            if not ma.any() or not mb.any():
                continue
            acc[n].append(w1(xa[ma], w_true_b[a][ma], xb[mb], w_true_b[b][mb]) * KMS)
    out = {}
    for n in COMP:
        v = np.array(acc[n], dtype=np.float64)
        lo, hi = pct_ci(v)
        out[n] = dict(mean=float(np.nanmean(v)), sd=float(np.nanstd(v, ddof=1)),
                      lo=lo, hi=hi)
    out["n_eff_half"] = float(np.mean(n_eff_half)) if n_eff_half else float("nan")
    return out


def gen_halfsplit_bin(gen_b, rng, b_split):
    """W1 between the two K/2 halves of one model's draws: Monte-Carlo floor."""
    n_b, k, _ = gen_b.shape
    if k < 2:
        return {n: float("nan") for n in COMP}
    half = k // 2
    acc = {n: [] for n in COMP}
    for _ in range(b_split):
        perm = rng.permutation(k)
        a, b = gen_b[:, perm[:half]], gen_b[:, perm[half:2 * half]]
        wa = np.full(n_b, 1.0 / (n_b * half))
        for c, n in enumerate(COMP):
            xa, xb = a[:, :, c].reshape(-1), b[:, :, c].reshape(-1)
            ma, mb = np.isfinite(xa), np.isfinite(xb)
            if not ma.any() or not mb.any():
                continue
            acc[n].append(w1(xa[ma], np.repeat(wa, half)[ma],
                             xb[mb], np.repeat(wa, half)[mb]) * KMS)
    return {n: float(np.mean(v)) for n, v in acc.items()}


