def load_protocol():
    p = np.load(PROT_DIR / "eval_protocol.npz")
    prot = dict(
        eta_strict=p["eta_strict"],
        w_strict=np.asarray(p["w_strict"], dtype=np.float64),
        r=p["r_strict"], cth=p["cth_strict"], phi=p["phi_strict"],
        v_true=np.stack([p["vr_strict"], p["vth_strict"], p["vT_strict"]], axis=1),
        ir=p["ir_strict"], ic=p["ic_strict"], ip=p["ip_strict"],
        r_edges=p["r_edges"], cth_edges=p["cth_edges"], phi_edges=p["phi_edges"],
    )
    # integrity: the audit's own protocol copy must be the same evaluation set
    prot["audit_protocol_match"] = None
    alt = AUDIT_DIR / "eval_protocol.npz"
    if alt.exists():
        with np.load(alt) as q:
            same_eta = np.array_equal(q["eta_strict"], prot["eta_strict"])
            same_w = np.array_equal(q["w_strict"], p["w_strict"])
        prot["audit_protocol_match"] = bool(same_eta and same_w)
        assert prot["audit_protocol_match"], (
            f"regenerated protocol differs from {alt}; refusing to mix evaluation sets")
    return prot


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def choose_window(series):
    """Display window per component: the 0.05-99.95% range of the samples, km/s.

    The input is a mapping from component name to samples and must already be in
    km/s (the same key set is returned); the result is
    rounded outward to a multiple of 10 km/s.  It is persisted so the reported
    out-of-window mass fractions describe exactly the range that is drawn.  The
    window never enters a statistic: W1 always uses every sample.
    """
    win = {}
    for name in series:
        lo = np.nanpercentile(series[name], 0.05)
        hi = np.nanpercentile(series[name], 99.95)
        win[name] = [float(np.floor(lo / 10.0) * 10.0), float(np.ceil(hi / 10.0) * 10.0)]
    return win


def frac_out(v, w, lo, hi):
    ok = np.isfinite(v)
    tot = np.sum(w[ok])
    if tot <= 0:
        return float("nan")
    return float(np.sum(w[ok & (v < lo) | ok & (v > hi)]) / tot)


