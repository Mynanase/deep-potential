            cells = "".join((f"{stats[(m, b, n, 'k4')]['w1']:.4f}"
                             f"[{stats[(m, b, n, 'k4')]['w1_lo']:.4f},{stats[(m, b, n, 'k4')]['w1_hi']:.4f}]")
                            .rjust(22) for b in range(n_bins))
