def md_table(header, rows, fmt=None):
    fmt = fmt or (lambda x: x)
    lines = ["| " + " | ".join(str(h) for h in header) + " |",
             "| " + " | ".join("---" for _ in header) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(fmt(x)) for x in row) + " |")
    return "\n".join(lines)


def fnum(x, nd=4, dash=True):
    if x is None:
        return "—" if dash else ""
    try:
        xf = float(x)
    except (TypeError, ValueError):
        return str(x)
    if not np.isfinite(xf):
        return "undefined" if dash else ""
    return f"{xf:.{nd}f}"


def fpm(mean, lo=None, hi=None, nd=4):
    if mean is None or not np.isfinite(float(mean)):
        return "undefined"
    if lo is None or hi is None or not (np.isfinite(lo) and np.isfinite(hi)):
        return f"{float(mean):.{nd}f}"
    return f"{float(mean):.{nd}f} [{float(lo):.{nd}f}, {float(hi):.{nd}f}]"


