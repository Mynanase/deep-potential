    with open(OUT / "rcv_summary.json", "w") as f:
        json.dump(dict(meta=meta,
                       stats=[dict(model=m, bin=b, comp=n, comp_label=COMP_LABEL[n],
                                   sample=s, **v)
                              for (m, b, n, s), v in stats.items()],
                       corr=[dict(model=m, bin=b, pair="|".join(p),
                                  pair_label=PAIR_LABEL[p], sample=s, **v)
                             for (m, b, p, s), v in corr.items()],
                       ckpt_stability=[dict(model=m, ckpt=f"flow-{c}", bin=b,
                                            comp=n, comp_label=COMP_LABEL[n], w1_kms=v)
                                       for (m, c, b, n), v in ckptstab.items()]),
                  f, indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o))

    with open(OUT / "rcv_tables.md", "w") as f:
        f.write(build_markdown(list(range(n_bins)), edges, stats, corr, support, ref,
                               block, ckptstab, meta["protocol"], window))

    # ------------------------------------------------------------- stdout evidence
    print("\n=== W1 (km/s), k4, model | bin | 95% paired-bootstrap interval ===", flush=True)
