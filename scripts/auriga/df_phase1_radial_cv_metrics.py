              + "   k4 w128 " + "/".join(f"{stats[('w128', b, n, 'k4')]['w1']:.4f}" for n in COMP)
              + "   k4 w1024 " + "/".join(f"{stats[('w1024', b, n, 'k4')]['w1']:.4f}" for n in COMP),
